/* =====================================================================
   מערכת דיווח גנים, חברה עירונית אריאל
   01_create_schema.sql  |  שלב א'  |  גרסת PostgreSQL (Supabase)
   יצירת סכמות, טבלאות, אילוצים, תצוגות וטריגרים
   ---------------------------------------------------------------------
   הומר מגרסת SQL Server. עיקרי ההבדלים:
   * שמות טבלאות ועמודות ב-snake_case (מוסכמת PostgreSQL / Supabase).
   * הסכמה auth שונתה ל-access, כי ב-Supabase הסכמה auth שמורה למערכת.
   * BIT -> boolean, NVARCHAR -> varchar, DATETIME2 -> timestamptz (נשמר ב-UTC).
   * ROWVERSION -> עמודת row_version שעולה אוטומטית בכל עדכון.
   * JSON נשמר כ-jsonb (במקום NVARCHAR + ISJSON).
   * אבטחה: RLS מופעל על כל הטבלאות ואין גישה לתפקידים anon / authenticated.
     הגישה למסד תהיה רק מצד השרת (Vercel) עם מפתח service_role.
   מחיקה: אין מחיקה פיזית של ישויות עסקיות, רק is_active = false.
   הרצה: על פרויקט Supabase ריק, ב-SQL Editor, פעם אחת לכל סביבה.
   ===================================================================== */

BEGIN;

/* ---------- סכמות ---------- */
CREATE SCHEMA IF NOT EXISTS ref;     -- רשימות קבועות והגדרות
CREATE SCHEMA IF NOT EXISTS core;    -- נתוני מאסטר: ספקים, גנים, גננות, התקשרויות
CREATE SCHEMA IF NOT EXISTS ops;     -- דיווחים, אישורים, הודעות
CREATE SCHEMA IF NOT EXISTS access;  -- קודי אימות ונעילות (במקור: auth)
CREATE SCHEMA IF NOT EXISTS audit;   -- יומן פעולות
CREATE SCHEMA IF NOT EXISTS procy;   -- תשתית לחיבור לפרוסי (שלב ב')
CREATE SCHEMA IF NOT EXISTS stg;     -- ייבוא ודחויים

/* ---------- פונקציות עזר ---------- */

-- עדכון אוטומטי של updated_at בכל שינוי שורה
CREATE OR REPLACE FUNCTION ref.tg_set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

/* =====================================================================
   ref : רשימות קבועות
   ===================================================================== */

CREATE TABLE ref.school_years (
    school_year_id  smallint     NOT NULL CONSTRAINT pk_school_years PRIMARY KEY,  -- למשל 2026 = תשפ"ו (השנה שבה היא מסתיימת)
    hebrew_name     varchar(10)  NOT NULL CONSTRAINT uq_school_years_name UNIQUE,  -- תשפ"ו
    start_date      date         NOT NULL,
    end_date        date         NOT NULL,
    is_current      boolean      NOT NULL DEFAULT false,
    CONSTRAINT ck_school_years_dates CHECK (end_date > start_date)
);
CREATE UNIQUE INDEX ux_school_years_one_current ON ref.school_years (is_current) WHERE is_current;

CREATE TABLE ref.activity_domains (            -- תחום פעילות: ריתמיקה, תיאטרון, יוגה...
    domain_id       smallint     GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_activity_domains PRIMARY KEY,
    name_he         varchar(50)  NOT NULL CONSTRAINT uq_activity_domains_name UNIQUE,
    is_active       boolean      NOT NULL DEFAULT true
);

CREATE TABLE ref.engagement_types (            -- סוג התקשרות
    engagement_type_id           smallint     NOT NULL CONSTRAINT pk_engagement_types PRIMARY KEY,
    code                         varchar(20)  NOT NULL CONSTRAINT uq_engagement_types_code UNIQUE,
    name_he                      varchar(60)  NOT NULL,
    requires_supervisor_approval boolean      NOT NULL   -- חד פעמי ותוספת מיתרה דורשים אישור מפקחת
);

CREATE TABLE ref.session_types (               -- סוג מפגש בשורת דיווח
    session_type_id smallint     NOT NULL CONSTRAINT pk_session_types PRIMARY KEY,
    code            varchar(20)  NOT NULL CONSTRAINT uq_session_types_code UNIQUE,
    name_he         varchar(30)  NOT NULL,
    pay_multiplier  numeric(4,2) NOT NULL,   -- כפול = 2.00 (מתומחר כתעריף כפול)
    cap_units       smallint     NOT NULL,   -- כפול = 1 (נספר כמפגש אחד בתקרה)
    CONSTRAINT ck_session_types_values CHECK (pay_multiplier > 0 AND cap_units >= 0)
);

CREATE TABLE ref.report_statuses (
    status_id       smallint     NOT NULL CONSTRAINT pk_report_statuses PRIMARY KEY,
    code            varchar(30)  NOT NULL CONSTRAINT uq_report_statuses_code UNIQUE,
    name_he         varchar(40)  NOT NULL,
    is_final        boolean      NOT NULL,
    sort_order      smallint     NOT NULL
);

CREATE TABLE ref.rejection_reasons (           -- סיבות דחייה מרשימה סגורה
    rejection_reason_id smallint NOT NULL CONSTRAINT pk_rejection_reasons PRIMARY KEY,
    applies_to      varchar(10)  NOT NULL,   -- TEACHER | STAFF
    name_he         varchar(80)  NOT NULL,
    is_active       boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_rejection_reasons_applies_to CHECK (applies_to IN ('TEACHER','STAFF'))
);

CREATE TABLE ref.staff_roles (
    role_id         smallint     NOT NULL CONSTRAINT pk_staff_roles PRIMARY KEY,
    code            varchar(20)  NOT NULL CONSTRAINT uq_staff_roles_code UNIQUE,
    name_he         varchar(40)  NOT NULL
);

CREATE TABLE ref.holidays (                    -- חגים וימים ללא פעילות בגנים
    holiday_date    date         NOT NULL CONSTRAINT pk_holidays PRIMARY KEY,
    name_he         varchar(60)  NOT NULL,
    school_year_id  smallint     NULL CONSTRAINT fk_holidays_school_year REFERENCES ref.school_years (school_year_id)
);

CREATE TABLE ref.settings (                    -- הגדרות מערכת, במקום ערכים קבועים בקוד
    setting_key     varchar(60)  NOT NULL CONSTRAINT pk_settings PRIMARY KEY,
    setting_value   varchar(200) NULL,       -- NULL = טרם הוחלט
    value_type      varchar(10)  NOT NULL,   -- INT | DECIMAL | TEXT | BOOL
    description_he  varchar(300) NOT NULL,
    updated_at      timestamptz(0) NOT NULL DEFAULT now(),
    updated_by      varchar(100) NULL,
    CONSTRAINT ck_settings_type CHECK (value_type IN ('INT','DECIMAL','TEXT','BOOL'))
);
CREATE TRIGGER trg_settings_updated_at BEFORE UPDATE ON ref.settings
    FOR EACH ROW EXECUTE FUNCTION ref.tg_set_updated_at();

/* =====================================================================
   core : נתוני מאסטר
   ===================================================================== */

CREATE TABLE core.staff_users (                -- צוות אריאל: דבורה, צופיה, רפרנטיות
    staff_user_id   integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_staff_users PRIMARY KEY,
    full_name       varchar(100) NOT NULL,
    email           varchar(254) NOT NULL CONSTRAINT uq_staff_users_email UNIQUE,
    windows_login   varchar(100) NULL,       -- נשמר מהגרסה המקומית. בענן הכניסה תהיה לפי מייל
    role_id         smallint     NOT NULL CONSTRAINT fk_staff_users_role REFERENCES ref.staff_roles (role_id),
    is_active       boolean      NOT NULL DEFAULT true,
    created_at      timestamptz(0) NOT NULL DEFAULT now()
);

CREATE TABLE core.supervisors (                -- מפקחות גנים
    supervisor_id   integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_supervisors PRIMARY KEY,
    full_name       varchar(100) NOT NULL,
    email           varchar(254) NULL,
    mobile_phone    char(10)     NULL,
    is_active       boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_supervisors_phone CHECK (mobile_phone IS NULL OR mobile_phone ~ '^05[0-9]{8}$')
);

CREATE TABLE core.suppliers (                  -- ספקים / מפעילים
    supplier_id       integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_suppliers PRIMARY KEY,
    supplier_number   varchar(10)  NOT NULL CONSTRAINT uq_suppliers_number UNIQUE,  -- "מספר ספק" מהטבלה של דבורה, משמש גם לכניסה
    vat_number        varchar(9)   NULL,     -- מספר עוסק (רשות המסים), טרם נאסף
    name              varchar(150) NOT NULL,
    email             varchar(254) NULL,
    procy_supplier_id varchar(50)  NULL,     -- פרוסי: מזהה הספק במערכת השכר (שלב ב')
    is_active         boolean      NOT NULL DEFAULT true,
    created_at        timestamptz(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_suppliers_number CHECK (supplier_number ~ '^[0-9]{5,10}$'),
    CONSTRAINT ck_suppliers_vat    CHECK (vat_number IS NULL OR vat_number ~ '^[0-9]{9}$'),
    CONSTRAINT ck_suppliers_email  CHECK (email IS NULL OR email ~ '^.+@.+\..+$')
);
CREATE UNIQUE INDEX ux_suppliers_procy ON core.suppliers (procy_supplier_id) WHERE procy_supplier_id IS NOT NULL;

CREATE TABLE core.supplier_contacts (          -- אנשי קשר לספק (למשל תאטרון אגדתא: אביטל ואילנית)
    contact_id      integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_supplier_contacts PRIMARY KEY,
    supplier_id     integer      NOT NULL CONSTRAINT fk_supplier_contacts_supplier REFERENCES core.suppliers (supplier_id),
    full_name       varchar(100) NOT NULL,
    mobile_phone    char(10)     NOT NULL,   -- נייד לקוד אימות
    email           varchar(254) NULL,
    is_primary      boolean      NOT NULL DEFAULT false,
    can_login       boolean      NOT NULL DEFAULT true,
    is_active       boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_supplier_contacts_phone CHECK (mobile_phone ~ '^05[0-9]{8}$')
);
-- אותו נייד לא יכול להיות פעיל פעמיים אצל אותו ספק
CREATE UNIQUE INDEX ux_supplier_contacts_phone ON core.supplier_contacts (supplier_id, mobile_phone) WHERE is_active;
CREATE INDEX ix_supplier_contacts_supplier ON core.supplier_contacts (supplier_id);

CREATE TABLE core.kindergartens (              -- גנים
    kindergarten_id        integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_kindergartens PRIMARY KEY,
    kindergarten_code      char(6)      NOT NULL CONSTRAINT uq_kindergartens_code UNIQUE,  -- סמל גן, 6 ספרות
    name                   varchar(100) NOT NULL,
    address                varchar(200) NULL,
    supervisor_id          integer      NULL CONSTRAINT fk_kindergartens_supervisor REFERENCES core.supervisors (supervisor_id),
    referent_staff_user_id integer      NULL CONSTRAINT fk_kindergartens_referent REFERENCES core.staff_users (staff_user_id), -- אם רפרנטיות מחולקות לפי גנים
    is_manual_track        boolean      NOT NULL DEFAULT false,  -- מסלול טופס ידני (גננת שמסרבת לחתום דיגיטלית)
    is_active              boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_kindergartens_code CHECK (kindergarten_code ~ '^[0-9]{6}$')
);

CREATE TABLE core.teachers (                   -- גננות (כולל ממלאות מקום)
    teacher_id      integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_teachers PRIMARY KEY,
    full_name       varchar(100) NOT NULL,
    mobile_phone    char(10)     NOT NULL,
    email           varchar(254) NULL,
    is_active       boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_teachers_phone CHECK (mobile_phone ~ '^05[0-9]{8}$')
);
-- נייד מזהה גננת אחת בלבד (בסיס לקוד האימות)
CREATE UNIQUE INDEX ux_teachers_phone ON core.teachers (mobile_phone) WHERE is_active;

CREATE TABLE core.teacher_assignments (        -- שיבוץ גננת לגן, עם תאריכים (מחליפות, העברות)
    assignment_id   integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_teacher_assignments PRIMARY KEY,
    teacher_id      integer      NOT NULL CONSTRAINT fk_teacher_assignments_teacher REFERENCES core.teachers (teacher_id),
    kindergarten_id integer      NOT NULL CONSTRAINT fk_teacher_assignments_kg REFERENCES core.kindergartens (kindergarten_id),
    valid_from      date         NOT NULL,
    valid_to        date         NULL,       -- NULL = שיבוץ פעיל
    is_substitute   boolean      NOT NULL DEFAULT false,
    CONSTRAINT ck_teacher_assignments_dates CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
CREATE INDEX ix_teacher_assignments_kg ON core.teacher_assignments (kindergarten_id, valid_from, valid_to);
CREATE INDEX ix_teacher_assignments_teacher ON core.teacher_assignments (teacher_id);

CREATE TABLE core.supervisor_approvals (       -- אישור מפקחת להתקשרות חד פעמית / תוספת מיתרה
    supervisor_approval_id    integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_supervisor_approvals PRIMARY KEY,
    supervisor_id             integer      NOT NULL CONSTRAINT fk_supervisor_approvals_supervisor REFERENCES core.supervisors (supervisor_id),
    approved_on               date         NOT NULL,
    recorded_by_staff_user_id integer      NOT NULL CONSTRAINT fk_supervisor_approvals_staff REFERENCES core.staff_users (staff_user_id),
    attachment_path           varchar(400) NULL,   -- מסמך / מייל אישור סרוק (נתיב ב-Supabase Storage)
    notes                     varchar(500) NULL,
    created_at                timestamptz(0) NOT NULL DEFAULT now()
);

CREATE TABLE core.engagements (                -- התקשרות: ספק x גן x שנה x פעילות (שורה בטבלה המרכזת)
    engagement_id          integer       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_engagements PRIMARY KEY,
    school_year_id         smallint      NOT NULL CONSTRAINT fk_engagements_year REFERENCES ref.school_years (school_year_id),
    supplier_id            integer       NOT NULL CONSTRAINT fk_engagements_supplier REFERENCES core.suppliers (supplier_id),
    kindergarten_id        integer       NOT NULL CONSTRAINT fk_engagements_kg REFERENCES core.kindergartens (kindergarten_id),
    domain_id              smallint      NOT NULL CONSTRAINT fk_engagements_domain REFERENCES ref.activity_domains (domain_id),
    engagement_type_id     smallint      NOT NULL CONSTRAINT fk_engagements_type REFERENCES ref.engagement_types (engagement_type_id),
    tariff_per_session     numeric(10,2) NOT NULL, -- עלות למפגש לפי ההסכם
    max_sessions           smallint      NOT NULL, -- תקרת מפגשים שנתית
    annual_budget          numeric(12,2) NOT NULL, -- תקרה כספית שנתית ("שנתי לספק")
    supervisor_approval_id integer       NULL CONSTRAINT fk_engagements_sup_approval REFERENCES core.supervisor_approvals (supervisor_approval_id),
    source_note            varchar(300)  NULL,     -- הטקסט המקורי מעמודת "תחום הפעלה", לשקיפות
    source_row_number      integer       NULL,     -- מספר השורה באקסל המקורי
    is_active              boolean       NOT NULL DEFAULT true,
    created_at             timestamptz(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_engagements_values CHECK (tariff_per_session > 0 AND max_sessions > 0 AND annual_budget > 0)
);
CREATE INDEX ix_engagements_supplier ON core.engagements (supplier_id, school_year_id) INCLUDE (kindergarten_id, is_active);
CREATE INDEX ix_engagements_kg       ON core.engagements (kindergarten_id, school_year_id) INCLUDE (supplier_id, is_active);

CREATE TABLE core.work_orders (                -- הזמנות עבודה (הזמנה 1, הזמנה 2...) מול ההתקשרות
    work_order_id      integer       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_work_orders PRIMARY KEY,
    engagement_id      integer       NOT NULL CONSTRAINT fk_work_orders_engagement REFERENCES core.engagements (engagement_id),
    order_seq          smallint      NOT NULL, -- 1, 2, ...
    amount             numeric(12,2) NOT NULL,
    order_date         date          NULL,
    procy_order_number varchar(50)   NULL,     -- פרוסי: מספר ההזמנה (שלב ב')
    notes              varchar(300)  NULL,
    CONSTRAINT uq_work_orders_seq UNIQUE (engagement_id, order_seq),
    CONSTRAINT ck_work_orders_amount CHECK (amount >= 0)
);

CREATE TABLE core.cap_overrides (              -- אישור חריגה מתקרה על ידי רפרנטית
    cap_override_id           integer       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_cap_overrides PRIMARY KEY,
    engagement_id             integer       NOT NULL CONSTRAINT fk_cap_overrides_engagement REFERENCES core.engagements (engagement_id),
    extra_sessions            smallint      NULL,     -- כמה מפגשים נוספים אושרו
    extra_amount              numeric(12,2) NULL,     -- כמה כסף נוסף אושר
    reason                    varchar(500)  NOT NULL,
    approved_by_staff_user_id integer       NOT NULL CONSTRAINT fk_cap_overrides_staff REFERENCES core.staff_users (staff_user_id),
    approved_at               timestamptz(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_cap_overrides_something CHECK (coalesce(extra_sessions,0) > 0 OR coalesce(extra_amount,0) > 0)
);
CREATE INDEX ix_cap_overrides_engagement ON core.cap_overrides (engagement_id);

/* =====================================================================
   ops.notifications (יומן הודעות) + access : קודי אימות ונעילה
   ===================================================================== */

CREATE TABLE ops.notifications (               -- יומן כל SMS / שיחה / מייל, כולל תזכורות מתוזמנות
    notification_id     bigint       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_notifications PRIMARY KEY,
    channel             varchar(10)  NOT NULL, -- SMS | VOICE | EMAIL
    purpose             varchar(20)  NOT NULL, -- OTP | APPROVAL_REQUEST | REMINDER | ESCALATION | CAP_WARNING
    recipient_type      varchar(20)  NOT NULL, -- TEACHER | SUPPLIER_CONTACT | STAFF
    recipient_id        integer      NOT NULL,
    destination         varchar(254) NOT NULL, -- מספר / מייל בפועל
    report_id           integer      NULL,     -- FK מוגדר אחרי יצירת ops.reports
    scheduled_for       timestamptz(0) NOT NULL DEFAULT now(),
    sent_at             timestamptz(0) NULL,
    status              varchar(12)  NOT NULL DEFAULT 'QUEUED',
    provider_message_id varchar(100) NULL,     -- מזהה ההודעה אצל ספק ה-SMS (mgroup)
    error_text          varchar(500) NULL,
    created_at          timestamptz(0) NOT NULL DEFAULT now(),
    CONSTRAINT ck_notifications_channel   CHECK (channel IN ('SMS','VOICE','EMAIL')),
    CONSTRAINT ck_notifications_purpose   CHECK (purpose IN ('OTP','APPROVAL_REQUEST','REMINDER','ESCALATION','CAP_WARNING')),
    CONSTRAINT ck_notifications_recipient CHECK (recipient_type IN ('TEACHER','SUPPLIER_CONTACT','STAFF')),
    CONSTRAINT ck_notifications_status    CHECK (status IN ('QUEUED','SENT','DELIVERED','FAILED','CANCELLED'))
);
CREATE INDEX ix_notifications_queue ON ops.notifications (status, scheduled_for);
CREATE INDEX ix_notifications_dest  ON ops.notifications (destination, created_at);  -- הגבלת קצב שליחה לנייד

CREATE TABLE access.otp_requests (             -- קוד אימות: נשמר מוצפן, לעולם לא כטקסט
    otp_request_id  bigint       GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_otp_requests PRIMARY KEY,
    user_type       varchar(20)  NOT NULL, -- TEACHER | SUPPLIER_CONTACT
    user_id         integer      NOT NULL, -- teacher_id או contact_id
    login_key       varchar(10)  NOT NULL, -- סמל הגן או מספר הספק שהוזן
    mobile_phone    char(10)     NOT NULL, -- הנייד שנבחר מהרשימה המוסתרת
    channel         varchar(10)  NOT NULL, -- SMS | VOICE
    code_hash       bytea        NOT NULL, -- SHA-256 של הקוד + Salt
    code_salt       bytea        NOT NULL,
    created_at      timestamptz(0) NOT NULL DEFAULT now(),
    expires_at      timestamptz(0) NOT NULL, -- created_at + OtpTtlMinutes (5)
    attempt_count   smallint     NOT NULL DEFAULT 0,
    consumed_at     timestamptz(0) NULL,     -- הוזן נכון
    notification_id bigint       NULL CONSTRAINT fk_otp_requests_notification REFERENCES ops.notifications (notification_id),
    CONSTRAINT ck_otp_requests_user_type CHECK (user_type IN ('TEACHER','SUPPLIER_CONTACT')),
    CONSTRAINT ck_otp_requests_channel   CHECK (channel IN ('SMS','VOICE')),
    CONSTRAINT ck_otp_requests_expiry    CHECK (expires_at > created_at),
    CONSTRAINT ck_otp_requests_hash      CHECK (octet_length(code_hash) = 32 AND octet_length(code_salt) = 16)
);
CREATE INDEX ix_otp_requests_phone ON access.otp_requests (mobile_phone, created_at DESC);

CREATE TABLE access.phone_lockouts (           -- נעילה לפי נייד (לא לפי גן / ספק)
    mobile_phone    char(10)     NOT NULL CONSTRAINT pk_phone_lockouts PRIMARY KEY,
    failed_attempts smallint     NOT NULL DEFAULT 0,
    last_failed_at  timestamptz(0) NULL,
    locked_until    timestamptz(0) NULL      -- NULL או עבר = לא נעול
);

/* =====================================================================
   ops : דיווחים ואישורים
   ===================================================================== */

CREATE TABLE ops.reports (                     -- דיווח חודשי: התקשרות אחת, חודש אחד
    report_id                      integer      GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_reports PRIMARY KEY,
    engagement_id                  integer      NOT NULL CONSTRAINT fk_reports_engagement REFERENCES core.engagements (engagement_id),
    report_year                    smallint     NOT NULL,
    report_month                   smallint     NOT NULL,
    status_id                      smallint     NOT NULL CONSTRAINT fk_reports_status REFERENCES ref.report_statuses (status_id),
    submitted_by_contact_id        integer      NULL CONSTRAINT fk_reports_contact REFERENCES core.supplier_contacts (contact_id),
    submitted_at                   timestamptz(0) NULL,
    is_manual                      boolean      NOT NULL DEFAULT false,  -- הוזן ידנית ע"י הצוות (מסלול ידני)
    manual_scan_path               varchar(400) NULL,     -- סריקת הטופס הידני
    entered_by_staff_user_id       integer      NULL CONSTRAINT fk_reports_entered_by REFERENCES core.staff_users (staff_user_id),
    final_approved_by_staff_user_id integer     NULL CONSTRAINT fk_reports_approved_by REFERENCES core.staff_users (staff_user_id),
    final_approved_at              timestamptz(0) NULL,
    locked_at                      timestamptz(0) NULL,
    created_at                     timestamptz(0) NOT NULL DEFAULT now(),
    updated_at                     timestamptz(0) NOT NULL DEFAULT now(),
    row_version                    integer      NOT NULL DEFAULT 1,  -- מניעת דריסה בעריכה מקבילית (במקור: ROWVERSION)
    CONSTRAINT uq_reports_engagement_month UNIQUE (engagement_id, report_year, report_month),
    CONSTRAINT uq_reports_id_engagement    UNIQUE (report_id, engagement_id),  -- עבור FK מורכב משורות הדיווח
