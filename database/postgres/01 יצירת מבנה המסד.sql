-- ניצול התקרות לכל התקשרות: מפגשים, כסף, התראה וחסימה
CREATE VIEW core.vw_engagement_usage WITH (security_invoker = true) AS
WITH used AS (
    SELECT  r.engagement_id,
            sum(l.cap_units)::int  AS sessions_used,
            sum(l.line_amount)     AS amount_used
    FROM    ops.reports r
    JOIN    ops.report_lines l ON l.report_id = r.report_id
    JOIN    ref.report_statuses s ON s.status_id = r.status_id
    WHERE   s.code <> 'TEACHER_REJECTED'          -- דיווח שנדחה לא נספר
    GROUP BY r.engagement_id
), overrides AS (
    SELECT  engagement_id,
            sum(coalesce(extra_sessions,0)) AS extra_sessions,
            sum(coalesce(extra_amount,0))   AS extra_amount
    FROM    core.cap_overrides
    GROUP BY engagement_id
), cfg AS (   -- שורה אחת תמיד, גם אם ההגדרה חסרה או לא מספרית (ברירת מחדל 3)
    SELECT coalesce(max(CASE WHEN setting_value ~ '^[0-9]+$' THEN setting_value::int END), 3) AS warn_remaining
    FROM   ref.settings WHERE setting_key = 'CapWarnRemainingSessions'
)
SELECT  e.engagement_id,
        e.supplier_id,
        e.kindergarten_id,
        e.school_year_id,
        e.tariff_per_session,
        e.max_sessions  + coalesce(o.extra_sessions,0)   AS session_cap,
        e.annual_budget + coalesce(o.extra_amount,0)     AS amount_cap,
        coalesce(u.sessions_used,0)                      AS sessions_used,
        coalesce(u.amount_used,0)                        AS amount_used,
        e.max_sessions  + coalesce(o.extra_sessions,0) - coalesce(u.sessions_used,0) AS sessions_remaining,
        e.annual_budget + coalesce(o.extra_amount,0)   - coalesce(u.amount_used,0)   AS amount_remaining,
        -- התראה: נותרו 3 מפגשים או פחות, או נותר סכום של 3 מפגשים רגילים או פחות
        (e.max_sessions + coalesce(o.extra_sessions,0) - coalesce(u.sessions_used,0) <= c.warn_remaining
          OR e.annual_budget + coalesce(o.extra_amount,0) - coalesce(u.amount_used,0) <= e.tariff_per_session * c.warn_remaining) AS is_warning,
        -- חסימה: הגיע לתקרת מפגשים או לתקרת כסף
        (e.max_sessions + coalesce(o.extra_sessions,0) - coalesce(u.sessions_used,0) <= 0
          OR e.annual_budget + coalesce(o.extra_amount,0) - coalesce(u.amount_used,0) <= 0) AS is_blocked
FROM    core.engagements e
CROSS JOIN cfg c
LEFT JOIN used u      ON u.engagement_id = e.engagement_id
LEFT JOIN overrides o ON o.engagement_id = e.engagement_id;

-- הגננות הפעילות של גן, עם נייד מוסתר לבחירה במסך הכניסה
-- התאריך נקבע לפי שעון ישראל (במקור: לפי UTC), כדי ששיבוץ יתחיל ויסתיים בחצות של ישראל
CREATE VIEW core.vw_kindergarten_login_phones WITH (security_invoker = true) AS
SELECT  k.kindergarten_code,
        t.teacher_id,
        t.full_name,
        left(t.mobile_phone,3) || '-***' || right(t.mobile_phone,4) AS masked_phone,
        count(*) OVER (PARTITION BY k.kindergarten_id)              AS teachers_in_kg   -- 1 = לדלג על שלב הבחירה
FROM    core.kindergartens k
JOIN    core.teacher_assignments a ON a.kindergarten_id = k.kindergarten_id
JOIN    core.teachers t            ON t.teacher_id = a.teacher_id
WHERE   k.is_active AND t.is_active
  AND   a.valid_from <= (now() AT TIME ZONE 'Asia/Jerusalem')::date
  AND  (a.valid_to IS NULL OR a.valid_to >= (now() AT TIME ZONE 'Asia/Jerusalem')::date);

-- אנשי הקשר הפעילים של ספק, עם נייד מוסתר לבחירה במסך הכניסה
CREATE VIEW core.vw_supplier_login_phones WITH (security_invoker = true) AS
SELECT  s.supplier_number,
        c.contact_id,
        c.full_name,
        left(c.mobile_phone,3) || '-***' || right(c.mobile_phone,4) AS masked_phone,
        count(*) OVER (PARTITION BY s.supplier_id)                  AS contacts_for_supplier
FROM    core.suppliers s
JOIN    core.supplier_contacts c ON c.supplier_id = s.supplier_id
WHERE   s.is_active AND c.is_active AND c.can_login;

-- החוזה לפרוסי: מה ייצא עבור כל דיווח נעול. המבנה הזה הוא נקודת המוצא לאפיון החיבור בשלב ב'
CREATE VIEW procy.vw_reports_for_export WITH (security_invoker = true) AS
SELECT  r.report_id,
        r.report_year,
        r.report_month,
        s.supplier_number,
        s.vat_number,
        s.procy_supplier_id,
        k.kindergarten_code,
        y.hebrew_name                      AS school_year,
        et.code                            AS engagement_type,
        d.name_he                          AS domain,
        count(l.report_line_id)            AS visit_count,
        sum(l.cap_units)::int              AS session_units,
        sum(l.line_amount)                 AS total_amount,
        (SELECT w.procy_order_number
           FROM core.work_orders w
          WHERE w.engagement_id = e.engagement_id AND w.procy_order_number IS NOT NULL
          ORDER BY w.order_seq DESC
          LIMIT 1)                         AS procy_order_number,
        r.locked_at
FROM    ops.reports r
JOIN    ref.report_statuses st  ON st.status_id = r.status_id AND st.code = 'LOCKED'
JOIN    core.engagements e      ON e.engagement_id = r.engagement_id
JOIN    core.suppliers s        ON s.supplier_id = e.supplier_id
JOIN    core.kindergartens k    ON k.kindergarten_id = e.kindergarten_id
JOIN    ref.school_years y      ON y.school_year_id = e.school_year_id
JOIN    ref.engagement_types et ON et.engagement_type_id = e.engagement_type_id
JOIN    ref.activity_domains d  ON d.domain_id = e.domain_id
JOIN    ops.report_lines l      ON l.report_id = r.report_id
GROUP BY r.report_id, r.report_year, r.report_month, s.supplier_number, s.vat_number, s.procy_supplier_id,
         k.kindergarten_code, y.hebrew_name, et.code, d.name_he, e.engagement_id, r.locked_at;

/* =====================================================================
   טריגר: כל דיווח שעובר לסטטוס LOCKED נכנס אוטומטית לתור הייצוא לפרוסי
   ===================================================================== */
CREATE OR REPLACE FUNCTION ops.tg_reports_enqueue_procy() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE
    v_payload jsonb;
BEGIN
    IF NEW.status_id IS DISTINCT FROM OLD.status_id
       AND EXISTS (SELECT 1 FROM ref.report_statuses s WHERE s.status_id = NEW.status_id AND s.code = 'LOCKED')
       AND NOT EXISTS (SELECT 1 FROM procy.outbox o WHERE o.report_id = NEW.report_id AND o.status <> 'FAILED')
    THEN
        SELECT to_jsonb(v) INTO v_payload
        FROM   procy.vw_reports_for_export v
        WHERE  v.report_id = NEW.report_id;

        IF v_payload IS NOT NULL THEN   -- דיווח בלי שורות לא נכנס לתור (כמו במקור)
            INSERT INTO procy.outbox (report_id, payload) VALUES (NEW.report_id, v_payload);
        END IF;
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER trg_reports_enqueue_procy AFTER UPDATE OF status_id ON ops.reports
    FOR EACH ROW EXECUTE FUNCTION ops.tg_reports_enqueue_procy();

/* =====================================================================
   אבטחה: RLS על כל הטבלאות, ללא גישה לתפקידים הציבוריים של Supabase.
   השרת (Vercel) ניגש עם service_role, שעוקף RLS. מפתח זה לעולם לא נשלח לדפדפן.
   ===================================================================== */
DO $$
DECLARE
    r record;
    sch text;
BEGIN
    FOR r IN
        SELECT n.nspname AS sch, c.relname AS tbl
        FROM   pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE  c.relkind = 'r'
          AND  n.nspname IN ('ref','core','ops','access','audit','procy','stg')
    LOOP
        EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY', r.sch, r.tbl);
    END LOOP;

    FOREACH sch IN ARRAY ARRAY['ref','core','ops','access','audit','procy','stg'] LOOP
        EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA %I FROM PUBLIC', sch);
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
            EXECUTE format('REVOKE ALL ON SCHEMA %I FROM anon, authenticated', sch);
            EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM anon, authenticated', sch);
            EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA %I FROM anon, authenticated', sch);
        END IF;
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
            EXECUTE format('GRANT USAGE ON SCHEMA %I TO service_role', sch);
            EXECUTE format('GRANT ALL ON ALL TABLES IN SCHEMA %I TO service_role', sch);
            EXECUTE format('GRANT ALL ON ALL SEQUENCES IN SCHEMA %I TO service_role', sch);
            EXECUTE format('GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA %I TO service_role', sch);
        END IF;
    END LOOP;
END $$;

